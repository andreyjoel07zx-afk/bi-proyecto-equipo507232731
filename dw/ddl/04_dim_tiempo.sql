INSERT INTO dw.dim_tiempo (sk_tiempo, fecha, dia, nombre_dia, dia_semana, es_fin_semana,
                           es_festivo, mes, nombre_mes, trimestre, semestre, anio)
SELECT CAST(TO_CHAR(d, 'YYYYMMDD') AS INTEGER),
       d::DATE,
       EXTRACT(DAY FROM d),
       (ARRAY['Lunes','Martes','Miércoles','Jueves','Viernes','Sábado','Domingo'])[EXTRACT(ISODOW FROM d)],
       EXTRACT(ISODOW FROM d),
       EXTRACT(ISODOW FROM d) IN (6, 7),
       EXISTS (SELECT 1 FROM festivos f WHERE f.fecha = d::DATE),
       EXTRACT(MONTH FROM d),
       (ARRAY['Enero','Febrero','Marzo','Abril','Mayo','Junio','Julio','Agosto',
              'Septiembre','Octubre','Noviembre','Diciembre'])[EXTRACT(MONTH FROM d)],
       EXTRACT(QUARTER FROM d),
       CASE WHEN EXTRACT(MONTH FROM d) <= 6 THEN 1 ELSE 2 END,
       EXTRACT(YEAR FROM d)
FROM generate_series(DATE '2022-01-01', DATE '2025-12-31', INTERVAL '1 day') AS d;
